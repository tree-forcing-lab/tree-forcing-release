#!/usr/bin/env python3
"""Write prompt_examples.md: one real prompt per condition, copied from the files in ../data.

    cd B_khop/results && python3 -I make_prompt_examples.py

Every eval set: the first k = 3 item (blind: the k = 3 copy of the khop_ca_fwd item). Training rows: the first
k = 3 row of train_kh (chain) and its train_k1 twin (same statements, hop-1 query). GSM: the first of the 249
primary items, as plain and as its rc2 hint row (pfx_table.cells). The model sees the prompt plus "\\n\\nAnswer:".
"""
import json, os, sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "code"))
import pfx_table as PFX  # noqa: E402

D = os.path.join(ROOT, "data", "eval")


def rows(p):
    return [json.loads(l) for l in open(p) if l.strip()]


out = ["# Prompt examples", "",
       "Generated by `make_prompt_examples.py` from `../data`. The model reads the prompt plus `\\n\\nAnswer:` and the "
       "readout is the arg max over the letters A-E.", ""]


def block(title, r, note=""):
    out.append(f"## {title}")
    out.append("")
    out.append(f"item_id `{r['item_id']}`, gold **{r['gold_label']}**{note}")
    out.append("")
    out.append("```")
    out.append(r["prompt"])
    out.append("```")
    out.append("")


for s in ["khop_ca_fwd", "khop_ca_rev", "khop_wp_fwd", "khop_wp_rev", "khop_vb_fwd", "khop_vb_rev", "khop_cag_fwd",
          "khop_ca_fwd_qs", "khop_blind"]:
    r = [x for x in rows(os.path.join(D, "khop", s + ".jsonl")) if x["k"] == 3][0]
    block(f"Eval set {s} (k = 3)", r)
kh = [x for x in rows(os.path.join(D, "khop", "train_kh.jsonl")) if x["group"].endswith("/k3")][0]
k1 = {x["item_id"]: x for x in rows(os.path.join(D, "khop", "train_k1.jsonl"))}[kh["item_id"] + "-k1"]
block("Training row, train_kh (chain, k = 3)", kh, "; target = the gold letter")
block("Training row, train_k1 (the same statements, hop-1 query: the K1 / K1X control)", k1, "; target = the gold letter")
h = PFX.load_hints(os.path.join(D, "hint"))
cl = PFX.cells(h)
iid = PFX.primary_items(cl)[0]
block("GSM plain (hint_plain, a primary item)", h["hint_plain"][iid])
s, r2 = cl[iid][2]
block(f"GSM rc2 cell of the same item ({s}: the true worked steps are shown and 2 serial steps are left)", r2)
open(os.path.join(HERE, "prompt_examples.md"), "w").write("\n".join(out))
print("\n".join(out)[:3000])
